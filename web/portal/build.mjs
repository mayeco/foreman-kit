// Builds the embedded Web Portal assets into internal/assets/portal_ui/:
//   portal.css  - Tailwind CSS 4 + daisyUI 5, compiled from input.css
//   icons.svg   - a Lucide sprite holding only the icons the templates use
//   fonts/      - the self-hosted woff2 files referenced by input.css
// Run `npm ci && npm run build` in web/portal, then commit the outputs.
import { spawnSync, spawn } from 'node:child_process';
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, '../..');
const out = join(repo, 'internal/assets/portal_ui');
const watch = process.argv.includes('--watch');

// ---- icons ---------------------------------------------------------------------------
const iconSources = [join(out, 'templates'), join(out, 'js'), join(repo, 'internal/portal/page_helpers.go')];
const iconPatterns = [
  /\{\{-?\s*icon[cs]?\s+"([a-z0-9-]+)"/g, // template: {{icon "name"}} / {{iconc "name" "class"}}
  /\bico\('([a-z0-9-]+)'/g, // portal.js: ico('name')
  /Icon:\s*"([a-z0-9-]+)"/g, // Go: navItem{Icon: "name"}
  /data-icon="([a-z0-9-]+)"/g, // markup that names an icon for JS
  /\bicon"\s+"([a-z0-9-]+)"/g, // template: (dict "icon" "name") handed to a partial such as panel_head or empty
];

function walk(p) {
  const st = statSync(p);
  if (!st.isDirectory()) return [p];
  return readdirSync(p).flatMap((n) => walk(join(p, n)));
}

function buildIcons() {
  const names = new Set();
  const lucide = join(here, 'node_modules/lucide-static/icons');
  for (const file of iconSources.flatMap(walk)) {
    const text = readFileSync(file, 'utf8');
    for (const re of iconPatterns) for (const m of text.matchAll(re)) names.add(m[1]);
    // Go helpers pick icons by name in plain string literals (toneIcon, kindBadge): keep every
    // literal that names a Lucide icon.
    if (file.endsWith('.go')) {
      for (const m of text.matchAll(/"([a-z][a-z0-9-]*)"/g)) if (existsSync(join(lucide, `${m[1]}.svg`))) names.add(m[1]);
    }
  }
  // The Go files that build tab and nav items name their icons as Icon: "name" (page_chrome.go, page_system.go ...).
  const portalDir = join(repo, 'internal/portal');
  for (const n of readdirSync(portalDir)) {
    if (!n.endsWith('.go') || n.endsWith('_test.go') || n === 'page_helpers.go') continue;
    for (const m of readFileSync(join(portalDir, n), 'utf8').matchAll(/\bIcon:\s*"([a-z0-9-]+)"/g)) names.add(m[1]);
  }
  const symbols = [...names].sort().map((name) => {
    let svg;
    try {
      svg = readFileSync(join(lucide, `${name}.svg`), 'utf8');
    } catch {
      throw new Error(`unknown Lucide icon "${name}" (not in lucide-static/icons)`);
    }
    const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();
    return `<symbol id="${name}" viewBox="0 0 24 24">${inner}</symbol>`;
  });
  // The favicon is the brand mark: Lucide's git-merge on a clipped signal-cyan plate.
  const mark = readFileSync(join(lucide, 'git-merge.svg'), 'utf8').replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();
  writeFileSync(join(out, 'favicon.svg'),
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32"><path d="M0 0H24L32 8V32H8L0 24Z" fill="#3ee0f0"/>'
    + `<g transform="translate(4 4)" fill="none" stroke="#06202a" stroke-width="2.25" stroke-linecap="round" stroke-linejoin="round">${mark}</g></svg>\n`);
  writeFileSync(join(out, 'icons.svg'),
    `<svg xmlns="http://www.w3.org/2000/svg"><!-- Lucide icons (ISC license), generated by web/portal/build.mjs -->\n${symbols.join('\n')}\n</svg>\n`);
  console.log(`icons.svg: ${symbols.length} icons`);
}

// ---- fonts ---------------------------------------------------------------------------
const fonts = [
  ['chakra-petch', [500, 600, 700]],
  ['ibm-plex-sans', [400, 500, 600]],
  ['ibm-plex-mono', [400, 500]],
];
function copyFonts() {
  mkdirSync(join(out, 'fonts'), { recursive: true });
  for (const [family, weights] of fonts) {
    for (const w of weights) {
      const file = `${family}-latin-${w}-normal.woff2`;
      copyFileSync(join(here, 'node_modules/@fontsource', family, 'files', file), join(out, 'fonts', file));
    }
  }
  console.log('fonts: copied');
}

// ---- css -----------------------------------------------------------------------------
const tw = join(here, 'node_modules/.bin/tailwindcss');
const twArgs = ['-i', join(here, 'input.css'), '-o', join(out, 'portal.css'), '--minify'];

buildIcons();
copyFonts();
if (watch) {
  spawn(tw, [...twArgs, '--watch'], { stdio: 'inherit', cwd: here });
} else {
  const r = spawnSync(tw, twArgs, { stdio: 'inherit', cwd: here });
  process.exit(r.status ?? 1);
}
